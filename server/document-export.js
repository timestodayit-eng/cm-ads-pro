import {existsSync} from 'node:fs';
import {htmlEscape} from '../shared/copilot.js';

const safeFileName=(title,ext)=>(String(title||'document').normalize('NFKD').replace(/[^a-zA-Z0-9_-]+/g,'-').replace(/^-+|-+$/g,'').slice(0,70)||'document')+'.'+ext;
const safeCsv=s=>'"'+String(s??'').replaceAll('"','""')+'"';
const csvCell=s=>safeCsv(/^[=+@\-\t\r]/.test(String(s??''))?"'"+s:s);
export function printHtml(doc,version){
 const title=htmlEscape(version.title||doc.title);
 const sections=version.sections.map(s=>`<section><h2>${htmlEscape(s.heading)}</h2><div class="content">${htmlEscape(s.content).replaceAll('\n','<br>')}</div></section>`).join('');
 return `<!doctype html><html lang="bn"><head><meta charset="utf-8"><title>${title}</title><meta name="viewport" content="width=device-width,initial-scale=1"><style>
 @page{size:A4;margin:18mm}body{margin:36px auto;max-width:780px;color:#223047;background:#fff;font:15px/1.68 system-ui,"Noto Sans Bengali","Hind Siliguri",sans-serif}h1{font-size:27px;line-height:1.25;border-bottom:3px solid #2563eb;padding-bottom:15px}h2{font-size:19px;color:#143b63;margin:32px 0 12px;break-after:avoid}section{break-inside:auto}.content{white-space:normal}p,div{overflow-wrap:anywhere}small{color:#64748b}button{padding:12px 18px;border-radius:9px;border:1px solid #93a3bd;background:white;cursor:pointer}@media print{button{display:none}body{margin:0}}
 </style></head><body><button onclick="window.print()">Print / Save as PDF</button><h1>${title}</h1><small>Version ${version.version_no} · Generated by Ads Command Center · Data snapshot: ${htmlEscape(version.sources?.generatedAt||'Not provided')}</small>${sections}</body></html>`;
}
export async function exportDocument(doc,version,format){
 const title=version.title||doc.title;
 if(format==='html')return{content:Buffer.from(printHtml(doc,version)),mime:'text/html; charset=utf-8',name:safeFileName(title,'html')};
 if(format==='csv'){
  const cells=['Section','Content'],rows=[cells.map(csvCell).join(',')];
  for(const section of version.sections)rows.push([section.heading,section.content].map(csvCell).join(','));
  return{content:Buffer.from('\ufeff'+rows.join('\r\n')+'\r\n'),mime:'text/csv; charset=utf-8',name:safeFileName(title,'csv')};
 }
 if(format==='docx'){
  const d=await import('docx');
  const children=[new d.Paragraph({text:title,heading:d.HeadingLevel.TITLE}),new d.Paragraph({text:`Document version ${version.version_no} · ${new Date().toISOString().slice(0,10)}`,spacing:{after:260}})];
  for(const s of version.sections){children.push(new d.Paragraph({text:s.heading,heading:d.HeadingLevel.HEADING_1,spacing:{before:280,after:100}}));for(const paragraph of s.content.split(/\n{2,}/)){children.push(new d.Paragraph({text:paragraph,spacing:{after:130}}));}}
  const document=new d.Document({sections:[{properties:{},children}]});
  return{content:await d.Packer.toBuffer(document),mime:'application/vnd.openxmlformats-officedocument.wordprocessingml.document',name:safeFileName(title,'docx')};
 }
 if(format==='xlsx'){
  const Excel=(await import('exceljs')).default;
  const workbook=new Excel.Workbook();workbook.creator='Ads Command Center';
  const sheet=workbook.addWorksheet('Document',{views:[{state:'frozen',ySplit:1}]});
  sheet.columns=[{header:'Section',key:'heading',width:39},{header:'Content',key:'content',width:100}];
  sheet.getRow(1).font={bold:true};
  for(const s of version.sections)sheet.addRow({heading:s.heading,content:s.content});
  sheet.getColumn('content').alignment={wrapText:true,vertical:'top'};
  // Do not make user-generated cells executable formulas.
  for(let i=2;i<=sheet.rowCount;i++){for(const col of [1,2]){const c=sheet.getRow(i).getCell(col);c.value=String(c.value??'');}}
  return{content:Buffer.from(await workbook.xlsx.writeBuffer()),mime:'application/vnd.openxmlformats-officedocument.spreadsheetml.sheet',name:safeFileName(title,'xlsx')};
 }
 if(format==='pdf'){
  // PDFKit requires an embeddable font that covers the document script.
  // Provide PDF_FONT_PATH in Hostinger for Bangla documents (never bundle private font files).
  const PDF=(await import('pdfkit')).default;
  const fontPath=process.env.PDF_FONT_PATH||'';
  const fullText=[title,...version.sections.flatMap(s=>[s.heading,s.content])].join('');
  if(/[^\u0000-\u00ff]/.test(fullText)&&(!fontPath||!existsSync(fontPath)))throw Object.assign(new Error('For Bengali/non-Latin PDF export, configure PDF_FONT_PATH to an installed Unicode font on your server; use HTML Print to PDF meanwhile.'),{status:503,code:'PDF_UNICODE_FONT_REQUIRED'});
  return await new Promise((resolve,reject)=>{
   const chunks=[];const pdf=new PDF({size:'A4',margin:52,info:{Title:title,Author:'Ads Command Center'}});
   pdf.on('data',c=>chunks.push(c));pdf.on('error',reject);pdf.on('end',()=>resolve({content:Buffer.concat(chunks),mime:'application/pdf',name:safeFileName(title,'pdf')}));
   if(fontPath&&existsSync(fontPath))pdf.font(fontPath);
   pdf.fontSize(22).fillColor('#17365d').text(title,{lineGap:5});
   pdf.moveDown(0.8).fillColor('#64748b').fontSize(9).text(`Version ${version.version_no} | ${new Date().toISOString().slice(0,10)}`);
   for(const s of version.sections){pdf.moveDown(1).fillColor('#1c3e68').fontSize(14).text(s.heading,{continued:false});pdf.moveDown(0.3).fillColor('#253448').fontSize(10.5).text(s.content,{lineGap:3});}
   pdf.end();
  });
 }
 throw Object.assign(new Error('Choose html, pdf, docx, xlsx or csv.'),{status:400,code:'EXPORT_FORMAT_INVALID'});
}
